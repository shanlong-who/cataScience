test_that("import preserves identifiers when a type is supplied and supports extensionless uploads", {
  path <- tempfile()
  writeLines(c('id,value', '001,3', '002,'), path)
  data <- cata_read(path, format = "csv", col_types = readr::cols(id = readr::col_character()))
  expect_identical(data$id, c("001", "002"))
  expect_true(is.na(data$value[2]))
  expect_error(cata_read(path, format = "pdf"), "CSV")
  expect_error(cata_read(NULL), "valid file")
})

test_that("profiles and missing summaries handle empty and non-finite columns", {
  data <- data.frame(x = c(NA, Inf, 3), label = c("a", NA, "a"))
  profile <- cata_profile(data)
  expect_equal(profile$missing, c(1, 1))
  expect_equal(profile$minimum[1], 3)
  expect_equal(profile$nonfinite, c(1, 0))
  expect_equal(cata_missing(data)$missing, c(1, 1))
  expect_equal(sum(cata_missing(data, "pattern")$records), 3)
  expect_identical(attr(cata_missing(data, "pattern"), "variables"), names(data))
  expect_true(all(is.na(cata_profile(data[0, ])$missing_pct)))
  expect_equal(nrow(cata_missing(data[0, ], "record")), 0)
  expect_equal(nrow(cata_missing(data[0, ], "pattern")), 0)
})

test_that("review flags retain values and distinguish missingness from outliers", {
  x <- c(1:9, 100, NA, Inf)
  flags <- cata_flag_outliers(x)
  expect_identical(flags$value, x)
  expect_true(flags$flag[10])
  expect_true(is.na(flags$flag[11]))
  expect_true(flags$flag[12])
  expect_equal(cata_flag_outliers(c(18, 110, 111), limits = c(18, 110))$flag, c(FALSE, FALSE, TRUE))
  expect_true(all(is.na(cata_flag_outliers(c(NA_real_, NA_real_))$flag)))
  expect_error(cata_flag_outliers(1:3, limits = c(10, 1)), "ordered")
})

test_that("key checks distinguish repeated IDs, identical rows and missing keys", {
  data <- data.frame(id = c("A", "A", "B", "B", NA, ""), value = c(1, 2, 3, 3, 4, 5))
  check <- cata_check_keys(data, "id")
  expect_equal(check$summary$repeated_key_rows, 4)
  expect_equal(check$summary$identical_row_members, 2)
  expect_equal(check$summary$missing_key_rows, 2)
  expect_false(check$summary$key_is_unique)
  expect_equal(nrow(check$review_rows), 6)
  expect_equal(nrow(data), 6)
})

test_that("audited joins enforce cardinality and keep missing keys unmatched", {
  x <- data.frame(id = c("A", "A", "B", NA))
  y <- data.frame(key = c("A", "B", NA), label = c("first", "second", "missing"))
  joined <- cata_join(x, y, by = c(id = "key"))
  expect_equal(nrow(joined$data), 4)
  expect_equal(joined$audit$matched_left_rows, 3)
  expect_true(is.na(joined$data$label[4]))
  expect_equal(nrow(joined$unmatched_right), 1)
  expect_error(cata_join(x, rbind(y, y[1, ]), by = c(id = "key")), "match at most")
  expect_equal(nrow(cata_join(x, y, by = c(id = "key"), type = "inner")$data), 3)
})

test_that("invalid denominators are visible and counts are not silently recycled", {
  out <- cata_proportion(c(1, 0, 5, NA), c(2, 0, 3, 4))
  expect_equal(out$value, c(50, NA, NA, NA))
  expect_equal(out$status[2:3], c("Zero denominator", "Numerator exceeds denominator"))
  expect_error(cata_proportion(1:2, 1:3), "lengths")
  expect_equal(cata_proportion(1, c(2, 4))$value, c(50, 25))
})

test_that("status summaries account for every row and retain missing groups", {
  data <- data.frame(status = c("Yes", "No", "Unknown", NA, "", "Yes"), group = c("A", "A", "A", "A", "A", NA))
  out <- cata_count_status(data, "status", by = "group")
  expect_equal(out$records, c(5, 1))
  expect_equal(out$percent, c(50, 100))
  expect_equal(out$unknown, c(1, 0))
  expect_equal(out$blank, c(2, 0))
  expect_equal(out$records, out$yes + out$no + out$unknown + out$blank)
  expect_true(is.na(out$group[2]))
  expect_error(cata_count_status(data, "status", yes = "Yes", no = "Yes"), "distinct")
})

